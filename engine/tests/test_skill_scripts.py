"""Tests for the correction-mining skill's scripts (.apm/skills/correction-mining/scripts).

Transcript lines are written compact, as Claude Code writes them (the extractor pre-filters on `"type":"user"`)."""

import json
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile
import time
import unittest

SCRIPTS = pathlib.Path(__file__).resolve().parent.parent.parent / ".apm" / "skills" / "correction-mining" / "scripts"
PY = sys.executable


def session(path: pathlib.Path, texts):
    rows = []
    for i, t in enumerate(texts):
        rows.append({"type": "assistant", "message": {"content": [{"type": "text", "text": f"agent says {i}"}]}})
        rows.append({"type": "user", "timestamp": f"2026-11-1{i}T10:00:00Z", "message": {"content": t}})
    path.write_text("\n".join(json.dumps(r, separators=(",", ":")) for r in rows) + "\n", encoding="utf-8")


class ExtractTests(unittest.TestCase):
    def setUp(self):
        self.tmp = pathlib.Path(tempfile.mkdtemp(prefix="cm-extract-"))
        self.root = self.tmp / "projects"
        for name, texts in (("-home-me-src-A", ["no, I said use pnpm"]), ("-home-me-src-B-wt", ["looks good"])):
            (self.root / name).mkdir(parents=True)
            session(self.root / name / "11111111-old.jsonl", texts)
            old = time.time() - 3600
            os.utime(self.root / name / "11111111-old.jsonl", (old, old))
        session(self.root / "-home-me-src-A" / "22222222-live.jsonl", ["mining right now"])  # just written

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def extract(self, *args):
        return subprocess.run([PY, "-I", "-B", str(SCRIPTS / "extract_claude.py"), "--root", str(self.root),
                               "--out", str(self.tmp / "out"), *args], capture_output=True, text=True)

    def test_several_dash_led_globs_and_the_live_session_is_skipped(self):
        p = self.extract("--projects", "-home-me-src-A", "-home-me-src-B*", "--strip-prefix", "-home-me-src-")
        self.assertEqual(p.returncode, 0, p.stderr)
        rows = [json.loads(l) for l in (self.tmp / "out" / "turns.jsonl").read_text(encoding="utf-8").splitlines()]
        self.assertEqual(sorted(r["proj"] for r in rows), ["A", "B-wt"])
        self.assertTrue(next(r for r in rows if r["proj"] == "A")["flag"])
        self.assertIn("skipped sessions: -home-me-src-A/22222222 (live)", p.stdout)
        p = self.extract("--projects", "-home-me-src-A", "--include-live", "--exclude-session", "1111")
        texts = [json.loads(l)["text"] for l in (self.tmp / "out" / "turns.jsonl").read_text(encoding="utf-8").splitlines()]
        self.assertEqual(texts, ["mining right now"])

    def test_no_match_is_an_error(self):
        p = self.extract("--projects=nothing-here")
        self.assertEqual(p.returncode, 1)
        self.assertIn("no transcripts match", p.stderr)


class CheckRefsTests(unittest.TestCase):
    def setUp(self):
        self.root = pathlib.Path(tempfile.mkdtemp(prefix="cm-refs-"))
        files = {
            "src/app/main.py": "x = 1\n",
            "CLAUDE.md": "Run `src/app/main.py`; see `docs/gone.md` and `.claude/rules/py.md`. Branch `origin/main`.\n",
            ".claude/rules/py.md": "---\npaths:\n  - \"src/**/*.py\"\n---\nUse `main.py`.\n",
            ".claude/rules/old.md": "---\npaths: legacy/**\n---\nold\n",
            ".claude/rules/fyzxsflow-working-agreement.md": "<!-- generated by fyzxsflow install.py -->\nsee `nope/x.md`\n",
        }
        for rel, text in files.items():
            (self.root / rel).parent.mkdir(parents=True, exist_ok=True)
            (self.root / rel).write_text(text, encoding="utf-8")

    def tearDown(self):
        shutil.rmtree(self.root, ignore_errors=True)

    def test_dead_globs_and_paths_and_the_always_on_budget(self):
        p = subprocess.run([PY, "-I", "-B", str(SCRIPTS / "check_refs.py"), "--root", str(self.root)],
                           capture_output=True, text=True)
        self.assertEqual(p.returncode, 1, p.stdout + p.stderr)
        line = lambda doc: next(l for l in p.stdout.splitlines() if l.startswith(f"| {doc} |"))
        self.assertIn("docs/gone.md", line("CLAUDE.md"))
        self.assertNotIn("origin/main", line("CLAUDE.md"))
        self.assertNotIn("main.py,", line("CLAUDE.md"))
        self.assertIn("path-scoped", line(".claude/rules/py.md"))
        self.assertTrue(line(".claude/rules/py.md").endswith("| - | - |"))
        self.assertIn("legacy/**", line(".claude/rules/old.md"))
        gen = line(".claude/rules/fyzxsflow-working-agreement.md")
        self.assertIn("always (generated)", gen)
        self.assertNotIn("nope/x.md", gen)  # checked at its source, not here
        self.assertIn("across 2 docs", p.stdout)  # CLAUDE.md + the generated agreement load every session
        self.assertEqual(list(self.root.rglob("__pycache__")), [])


if __name__ == "__main__":
    unittest.main()
