"""Write host-native pointer files for every agentflow segment doc, so ordinary (non-flow) sessions on each
host follow the same conventions. One source: the pointers only say "read the segment doc".

  python -I engine/pointers.py [--root <repo>]            # write / refresh pointers
  python -I engine/pointers.py --check [--root <repo>]    # exit 1 if any pointer is missing, stale or edited

Hosts come from .agentflow/config.json -> docs.host_pointers (default ["claude", "copilot"]):
  claude  -> .claude/rules/agentflow-<segment>.md                       (frontmatter `paths:`)
  copilot -> .github/instructions/agentflow-<segment>.instructions.md   (frontmatter `applyTo:`)
Only files named agentflow-* are managed; hand-written rules and instructions are never touched.
Segment docs come from .agentflow/docs/segments/*.md (files starting with "_" are templates and skipped).
"""

import argparse
import json
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from docs_check import frontmatter_list  # noqa: E402

MARK = "<!-- generated by agentflow engine/pointers.py — do not edit; change the segment doc instead -->"
TARGETS = {
    "claude": (pathlib.Path(".claude/rules"), "agentflow-{seg}.md"),
    "copilot": (pathlib.Path(".github/instructions"), "agentflow-{seg}.instructions.md"),
}


def title_of(text: str, seg: str) -> str:
    m = re.search(r"^#\s+(?:Segment:\s*)?(.+)$", text, re.M)
    return (m.group(1).strip() if m else seg).replace('"', "'")


def body(doc_rel: str, has_pack: bool) -> str:
    extra = " and every file listed under its `pack:`" if has_pack else ""
    return (f"{MARK}\n\nBefore creating or changing files in this segment, read `{doc_rel}`{extra}, and follow its "
            "pattern, canonical examples and do/don't lists. Where the doc and the code disagree, follow the code "
            "and say so.\n")


def render(host: str, seg: str, globs: list, title: str, doc_rel: str, has_pack: bool) -> str:
    if host == "claude":
        fm = "---\npaths:\n" + "".join(f'  - "{g}"\n' for g in globs) + "---\n"
    else:
        fm = f'---\napplyTo: "{",".join(globs)}"\ndescription: "{title} conventions (agentflow segment)"\n---\n'
    return fm + "\n" + body(doc_rel, has_pack)


def expected(root: pathlib.Path, hosts: list) -> dict:
    out = {}
    seg_dir = root / ".agentflow" / "docs" / "segments"
    for doc in sorted(seg_dir.glob("*.md")) if seg_dir.is_dir() else []:
        if doc.name.startswith("_"):
            continue
        text = doc.read_text(encoding="utf-8")
        globs = frontmatter_list(text, "paths")
        if not globs:
            continue
        seg = doc.stem
        doc_rel = doc.relative_to(root).as_posix()
        has_pack = bool(frontmatter_list(text, "pack"))
        for host in hosts:
            folder, pattern = TARGETS[host]
            out[folder / pattern.format(seg=seg)] = render(host, seg, globs, title_of(text, seg), doc_rel, has_pack)
    return out


def managed(root: pathlib.Path, hosts: list) -> set:
    found = set()
    for host in hosts:
        folder, pattern = TARGETS[host]
        glob = pattern.format(seg="*")
        if (root / folder).is_dir():
            found |= {p.relative_to(root) for p in (root / folder).glob(glob)}
    return found


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--root", default=".")
    p.add_argument("--check", action="store_true")
    args = p.parse_args(argv)
    root = pathlib.Path(args.root).resolve()
    cfg = root / ".agentflow" / "config.json"
    hosts = ["claude", "copilot"]
    if cfg.exists():
        hosts = json.loads(cfg.read_text(encoding="utf-8")).get("docs", {}).get("host_pointers", hosts)
    unknown = [h for h in hosts if h not in TARGETS]
    if unknown:
        print(f"unknown host(s) in docs.host_pointers: {', '.join(unknown)}", file=sys.stderr)
        return 2

    want = expected(root, hosts)
    have = managed(root, list(TARGETS))
    stale = sorted(have - set(want))
    problems = []
    for rel, content in want.items():
        path = root / rel
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != content:
            if args.check:
                problems.append(f"{rel.as_posix()}: {'missing' if current is None else 'out of date or edited by hand'}")
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding="utf-8", newline="\n")
                print(f"wrote {rel.as_posix()}")
    for rel in stale:
        if args.check:
            problems.append(f"{rel.as_posix()}: no matching segment doc (stale)")
        else:
            (root / rel).unlink()
            print(f"removed {rel.as_posix()}")
    if args.check:
        for prob in problems:
            print(f"FAIL {prob}")
        print(f"pointers: {'pass' if not problems else 'fail'} ({len(want)} expected, {len(problems)} problems)")
        return 0 if not problems else 1
    print(f"pointers: {len(want)} in sync for {', '.join(hosts)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
