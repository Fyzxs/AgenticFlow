"""Audit a repo's hand-written agent docs: what loads when, how big it is, and which references are dead.

  python -I -B check_refs.py [--root .]

Docs checked: CLAUDE.md / AGENTS.md (any folder), .claude/CLAUDE.md, .github/copilot-instructions.md,
.claude/rules/*.md, .github/instructions/*.md, and hand-written .claude/agents|skills|commands and .github/agents
files. Generated host files (which say "generated by") are skipped, except generated rules/instructions, which
still count toward what loads every session (their references are checked at their source).
Reports per doc: load mode (always / path-scoped by `paths:` or `applyTo:` / on demand), size, scope globs that
match no file, and backticked paths that do not exist. Read-only; prints markdown. Exit 1 if anything is dead.
(.fyzxsflow/ docs are checked by .fyzxsflow/package/engine/docs_check.py once FyzxsFlow is initialised.)
"""
import argparse, fnmatch, os, pathlib, re, subprocess, sys

ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
ap.add_argument('--root', default='.')
root = pathlib.Path(ap.parse_args().root).resolve()
sys.stdout.reconfigure(encoding='utf-8')

SKIP_DIRS = {'.git', 'node_modules', '.venv', 'venv', '__pycache__', 'bin', 'obj', 'dist', 'build', '.fyzxsflow'}


def repo_files():
    p = subprocess.run(['git', 'ls-files', '-co', '--exclude-standard'], cwd=root, capture_output=True, text=True)
    if p.returncode == 0 and p.stdout.strip():
        return sorted(set(p.stdout.splitlines()))
    out = []
    for d, dirs, fs in os.walk(root):
        dirs[:] = [x for x in dirs if x not in SKIP_DIRS]
        out += [os.path.relpath(os.path.join(d, f), root).replace(os.sep, '/') for f in fs]
    return sorted(out)


FILES = repo_files()
DIRS = {'/'.join(f.split('/')[:i]) for f in FILES for i in range(1, f.count('/') + 1)}


def matches(glob):
    g = glob.strip().strip('"\'').removeprefix('./') or '**'
    if g.startswith('/'):
        g = g[1:]
    pats = {g, g.replace('**/', '')}  # '**/' also matches zero folders
    return any(fnmatch.fnmatch(f, p) for f in FILES for p in pats) or g.rstrip('/') in DIRS


def frontmatter(text):
    m = re.match(r'\A---\n(.*?)\n---\n', text, re.S)
    if not m:
        return {}
    fm, key = {}, None
    for line in m.group(1).splitlines():
        if re.match(r'^[A-Za-z][\w-]*:', line):
            key, v = line.split(':', 1)
            fm[key] = [x.strip().strip('"\'') for x in re.split(r',(?![^{]*})', v) if x.strip()] if v.strip() else []
        elif key and line.strip().startswith('- '):
            fm[key].append(line.strip()[2:].strip().strip('"\''))
    return fm


def docs():
    for f in FILES:
        name = f.rsplit('/', 1)[-1]
        if name in ('CLAUDE.md', 'AGENTS.md', 'CLAUDE.local.md') or f == '.github/copilot-instructions.md':
            yield f
        elif re.match(r'^(\.claude/(rules|agents|commands)|\.github/(instructions|agents))/.*\.md$', f) \
                or re.match(r'^(\.claude|\.github)/skills/[^/]+/SKILL\.md$', f):
            yield f


PATHLIKE = re.compile(r'`([^`\s]+)`')
EXT = re.compile(r'\.(md|py|cs|ts|tsx|js|json|ya?ml|toml|csproj|sln|sh|ps1|txt|sql|go|rs|java)$')


def exists(t, doc):
    """t names something in the repo: from the root, from the doc's folder or any folder above it, as a path suffix
    anywhere, or (a glob) matching some file or file name."""
    t = re.sub(r':\d+(-\d+)?$', '', t).removeprefix('./')
    parent = pathlib.PurePosixPath(doc).parent
    bases = [''] + [str(p) + '/' for p in [parent, *parent.parents] if str(p) != '.']
    cands = {os.path.normpath(b + t).replace(os.sep, '/') for b in bases}
    if any(c in FILES or c.rstrip('/') in DIRS for c in cands):
        return True
    if '*' in t:
        return any(matches(c) for c in cands) or any(fnmatch.fnmatch(f.rsplit('/', 1)[-1], t) for f in FILES)
    return any(f.endswith('/' + t) for f in FILES) or any(d.endswith('/' + t.rstrip('/')) for d in DIRS)


def dead_refs(doc, text):
    out = []
    for tok in sorted(set(PATHLIKE.findall(text))):
        t = tok.rstrip('.,:;)')
        if '://' in t or t.startswith(('$', '-', '~', '<', '@')) or re.search(r'[{}()<>|]', t):
            continue  # URLs, variables, options, placeholders like <run>
        if re.fullmatch(r'\*?\.\w+', t):
            continue  # a bare extension like `.cs`
        if '/' not in t and not EXT.search(re.sub(r':\d+$', '', t)):
            continue  # not a path
        top = t.removeprefix('./').split('/')[0]
        if '/' in t and not EXT.search(t) and '*' not in t and top not in DIRS:
            continue  # `origin/main`, `owner/repo`: not a repo path unless its top folder exists
        if t.startswith(('.fyzxsflow/', 'reports/', 'runs/', 'runner/', 'gates/')):
            continue  # FyzxsFlow's own paths, checked by docs_check.py once the repo is initialised
        if not exists(t, doc):
            out.append(t)
    return out


def generated(d, text):
    """Host files FyzxsFlow (or another installer) wrote: their source is checked upstream, not here."""
    if 'generated by' in text[:600]:
        return True
    pkg = root / '.fyzxsflow' / 'package'
    name = d.rsplit('/', 1)[-1].replace('.agent.md', '.md')
    return pkg.is_dir() and (
        d.startswith(('.claude/agents/', '.github/agents/')) and (pkg / 'agents' / name.replace('.md', '.agent.md')).exists()
        or d.startswith('.claude/commands/') and (pkg / 'prompts' / name.replace('.md', '.prompt.md')).exists()
        or '/skills/' in d and ((pkg / 'prompts' / f"{d.split('/')[2]}.prompt.md").exists()
                                or (pkg / 'skills' / d.split('/')[2]).is_dir()))


rows, dead = [], 0
for d in docs():
    text = (root / d).read_text(encoding='utf-8', errors='replace')
    gen = generated(d, text)  # still loads and costs context; its references are checked at its source
    if gen and not d.startswith(('.claude/rules/', '.github/instructions/')):
        continue  # generated agents/commands/skills load on demand: not part of the always-on budget
    fm = frontmatter(text)
    scope = fm.get('paths') or fm.get('applyTo') or fm.get('globs') or []
    if d.endswith(('CLAUDE.md', 'AGENTS.md', 'copilot-instructions.md')):
        mode = 'always' if d.count('/') == 0 or d.startswith('.claude/') else f'when working under {d.rsplit("/", 1)[0]}/'
    elif d.startswith(('.claude/rules/', '.github/instructions/')):
        mode = 'always' if not scope or scope == ['**'] else 'path-scoped'
    else:
        mode = 'on demand (agent/skill/command)'
    bad_scope = [g for g in scope if g != '**' and not matches(g)]
    refs = [] if gen else dead_refs(d, text)
    if gen:
        mode += ' (generated)'
    dead += len(bad_scope) + len(refs)
    rows.append((d, mode, len(text.encode('utf-8')), text.count('\n') + 1, scope, bad_scope, refs))

print(f'# Agent-doc audit: {root.name}\n')
print('| doc | loads | bytes | lines | scope globs matching nothing | dead references |')
print('|---|---|---|---|---|---|')
for d, mode, b, n, scope, bad, refs in rows:
    print(f"| {d} | {mode}{' (' + ', '.join(scope) + ')' if scope else ''} | {b} | {n} | "
          f"{', '.join(bad) or '-'} | {', '.join(refs[:12]) + (' …' if len(refs) > 12 else '') or '-'} |")
always = sum(b for _, m, b, *_ in rows if m.startswith('always'))
print(f'\nAlways loaded: {always} bytes across {sum(1 for r in rows if r[1].startswith("always"))} docs. '
      f'Dead: {dead}. Backticked tokens are a heuristic: confirm each before proposing a fix.')
sys.exit(1 if dead else 0)
